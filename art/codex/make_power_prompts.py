    title, refs, scene = JOBS[name]
    text = (f"\n## 这一张：能力图标“{title}”\n- 画面：{scene}构图居中。\n\n"
            f"保存为：`generated/{name}.png`\n\n最后只回复一行：保存的路径和图片像素尺寸。\n")
